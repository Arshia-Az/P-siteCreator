import uuid
from django.conf import settings
from django.db import models
from django.db.models.signals import post_delete
from django.dispatch import receiver
from django.utils import timezone


def media_path(instance, filename):
    return f"builder/media/{timezone.now():%Y/%m}/{uuid.uuid4().hex}.webp"


def thumb_path(instance, filename):
    return f"builder/media/thumbs/{timezone.now():%Y/%m}/{uuid.uuid4().hex}.webp"


class PageCategory(models.Model):
    name = models.CharField(max_length=80, unique=True)
    slug = models.SlugField(max_length=100, unique=True, allow_unicode=True)
    description = models.CharField(max_length=300, blank=True, default="")
    color = models.CharField(max_length=7, default="#f2a63a")
    parent = models.ForeignKey("self", null=True, blank=True, on_delete=models.SET_NULL, related_name="children")
    order = models.PositiveIntegerField(default=0)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["order", "name"]
        verbose_name = "دسته‌بندی صفحه"
        verbose_name_plural = "دسته‌بندی صفحات"

    def __str__(self):
        return self.name


class BuilderPage(models.Model):
    STATUS_CHOICES = [("draft", "پیش‌نویس"), ("published", "منتشر شده")]

    title = models.CharField(max_length=200)
    # URL path such as "about" or "services/web-design" (validated/normalised by paths.py; unique)
    slug = models.CharField(max_length=220, unique=True)
    status = models.CharField(max_length=10, choices=STATUS_CHOICES, default="draft")
    category = models.ForeignKey(PageCategory, null=True, blank=True, on_delete=models.SET_NULL, related_name="pages")
    allow_comments = models.BooleanField(default=True)
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")

    seo_title = models.CharField(max_length=200, blank=True, default="")
    meta_description = models.CharField(max_length=300, blank=True, default="")
    meta_keywords = models.CharField(max_length=300, blank=True, default="")
    og_image = models.URLField(blank=True, default="")
    robots = models.CharField(max_length=20, default="index")
    schema_type = models.CharField(max_length=50, default="WebPage")
    schema_json = models.TextField(blank=True, default="")
    background_color = models.CharField(max_length=9, default="#ffffff")

    # Source of truth for editing: { blocks, headerOverride, footerOverride }
    content_json = models.JSONField(default=dict)
    # Compiled output served to visitors (regenerated by the builder on every save).
    rendered_html = models.TextField(blank=True, default="")

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-updated_at"]

    def __str__(self):
        return self.title


class SlugRedirect(models.Model):
    """Old address -> page, so changing a page's URL never produces a dead link (301 redirect)."""
    old_path = models.CharField(max_length=220, unique=True)
    page = models.ForeignKey(BuilderPage, on_delete=models.CASCADE, related_name="redirects")
    created_at = models.DateTimeField(auto_now_add=True)


class MediaGroup(models.Model):
    name = models.CharField(max_length=80, unique=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["name"]

    def __str__(self):
        return self.name


class MediaAsset(models.Model):
    # group=None means the built-in "بی‌گروه" (ungrouped) bucket.
    group = models.ForeignKey(MediaGroup, null=True, blank=True, on_delete=models.SET_NULL, related_name="assets")
    file = models.ImageField(upload_to=media_path)
    thumb = models.ImageField(upload_to=thumb_path, blank=True, null=True)
    width = models.PositiveIntegerField(default=0)
    height = models.PositiveIntegerField(default=0)
    size_bytes = models.PositiveIntegerField(default=0)
    title = models.CharField(max_length=150, blank=True, default="")
    alt = models.CharField(max_length=200, blank=True, default="")
    original_name = models.CharField(max_length=200, blank=True, default="")
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return self.title or self.original_name


@receiver(post_delete, sender=MediaAsset)
def _delete_media_files(sender, instance, **kwargs):
    for f in (instance.file, instance.thumb):
        if f:
            f.delete(save=False)


class PageComment(models.Model):
    STATUS = [("pending", "در انتظار تأیید"), ("approved", "تأیید شده"), ("rejected", "رد شده"), ("spam", "هرزنامه")]

    page = models.ForeignKey(BuilderPage, on_delete=models.CASCADE, related_name="comments")
    parent = models.ForeignKey("self", null=True, blank=True, on_delete=models.CASCADE, related_name="replies")
    author_name = models.CharField(max_length=60)
    author_email = models.EmailField(blank=True, default="")
    body = models.TextField(max_length=2000)
    status = models.CharField(max_length=10, choices=STATUS, default="pending", db_index=True)
    is_read = models.BooleanField(default=False, db_index=True)
    is_admin_reply = models.BooleanField(default=False)
    user = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    ip_hash = models.CharField(max_length=64, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.author_name}: {self.body[:30]}"


class SiteSettings(models.Model):
    """Singleton (pk=1): site-wide colours, global header/footer and the homepage."""
    colors = models.JSONField(default=dict, blank=True)
    header_json = models.JSONField(null=True, blank=True)   # {"cfg": {...}, "html": "<rendered>"}
    footer_json = models.JSONField(null=True, blank=True)
    home_page = models.ForeignKey(BuilderPage, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    updated_at = models.DateTimeField(auto_now=True)

    @classmethod
    def load(cls):
        obj, _ = cls.objects.get_or_create(pk=1)
        return obj


class LayoutTemplate(models.Model):
    KINDS = [("header", "هدر"), ("footer", "فوتر")]
    kind = models.CharField(max_length=10, choices=KINDS, db_index=True)
    name = models.CharField(max_length=80)
    doc = models.JSONField(default=dict)       # builder document
    render = models.JSONField(default=dict, blank=True)
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
        unique_together = [("kind", "name")]
